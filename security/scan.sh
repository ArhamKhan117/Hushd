#!/usr/bin/env bash
# Every security check in one run (`pnpm security`). Writes security/report.md and
# security/near-scan.md, and exits non-zero if any check fails.
#
# Needs: cargo-audit and cargo-deny (`cargo install --locked cargo-audit cargo-deny`).
set -uo pipefail
cd "$(dirname "$0")/.."
ROOT=$(pwd)
OUT="$ROOT/security/report.md"
LOG=$(mktemp -d)
trap 'rm -rf "$LOG"' EXIT
failed=0
rows=""

for tool in cargo-audit cargo-deny; do
  command -v "$tool" >/dev/null || { echo "$tool is missing: cargo install --locked cargo-audit cargo-deny"; exit 2; }
done

# step <name> <what it checks> <dir> <command...>: runs it, keeps the log, adds a row
step() {
  local name=$1 what=$2 dir=$3
  shift 3
  local log="$LOG/$(echo "$name" | tr ' /' '__').log"
  if (cd "$dir" && "$@") >"$log" 2>&1; then
    result="Pass"
  else
    result="**Fail**"
    failed=1
  fi
  local detail=""
  case "$name" in
    near-scan\ \(*) detail=$(grep -E "hits:" "$log" | tail -1) ;;
    *self-test) detail=$(grep -oE "[0-9]+ passed; [0-9]+ failed" "$log" | head -1) ;;
    cargo\ audit*)
      local crates allowed
      crates=$(grep -oE "\([0-9]+ crate dependencies\)" "$log" | tr -d '()')
      allowed=$(grep -oE "[0-9]+ allowed warnings?" "$log")
      detail=$(grep -oE "[0-9]+ vulnerabilit(y|ies) found" "$log" || echo "no known vulnerabilities in $crates")
      # advisories excepted in .cargo/audit.toml, each with its reason there and in SECURITY.md
      local ignored
      ignored=$(grep -oE "RUSTSEC-[0-9]+-[0-9]+" "$dir/.cargo/audit.toml" 2>/dev/null | tr '\n' ' ' | sed 's/ $//')
      [ -n "$ignored" ] && detail="$detail apart from $ignored (host-side test VM only, in no contract's wasm)"
      [ -n "$allowed" ] && detail="$detail; $allowed (unmaintained crates, listed in SECURITY.md)" ;;
    cargo\ deny*) detail=$(grep -E "advisories" "$log" | tail -1) ;;
    clippy*) detail=$(grep -cE "^(warning|error)" "$log" | sed 's/^0$/no warnings/') ;;
    pnpm*) detail=$(grep -E "^Severity" "$log" | sed 's/Severity: //') && detail="${detail:-none}, below the moderate bar (see SECURITY.md)" ;;
  esac
  detail=$(echo "$detail" | sed 's/|/\\|/g; s/  */ /g; s/ *$//')
  echo "$result  $name  $detail"
  rows+="| $name | $what | $result | ${detail:-clean} |"$'\n'
}

step "near-scan (contracts)" "22 NEAR detector classes on the parsed contract source; every hit needs a written reason" contracts \
  cargo run -q -p near-scan -- --md "$ROOT/security/near-scan.md"
step "near-scan self-test" "A deliberately broken contract trips each classic detector" contracts \
  cargo test -q -p near-scan
step "cargo audit (contracts)" "RustSec advisories for every crate in contracts/Cargo.lock" contracts cargo audit
step "cargo audit (matcher)" "RustSec advisories for the enclave's crates" matcher cargo audit
step "cargo deny (contracts)" "Advisories, licenses, crate sources, wildcard versions" contracts cargo deny check
step "cargo deny (matcher)" "Advisories, licenses, crate sources, wildcard versions" matcher cargo deny check
step "clippy (contracts)" "Rust lints, warnings as errors, contracts and tests" contracts \
  cargo clippy -q -p hushd-pool -p hushd-desk -p hushd-board -p hushd-token -p near-scan --all-targets -- -D warnings
step "clippy (matcher)" "Rust lints, warnings as errors" matcher cargo clippy -q --all-targets -- -D warnings
step "pnpm audit" "npm advisories for production JS dependencies, moderate and above" . \
  pnpm audit --prod --audit-level moderate

{
  echo "# Security scan report"
  echo
  # the reports themselves do not count as changes
  dirty=$(git status --porcelain 2>/dev/null | grep -qvE "^.. security/(report|near-scan)\.md$" && echo " plus uncommitted changes")
  echo "Generated by \`pnpm security\` (security/scan.sh) on $(date -u +%Y-%m-%d) at commit \`$(git rev-parse --short HEAD 2>/dev/null || echo unknown)\`$dirty. Do not edit by hand."
  echo
  echo "Tools: $(rustc --version | cut -d' ' -f1-2), $(cargo clippy --version | cut -d' ' -f1-2), $(cargo audit --version | sed 's/cargo-audit-audit/cargo-audit/'), $(cargo deny --version), pnpm $(pnpm --version)."
  echo
  echo "| Check | What it covers | Result | Summary |"
  echo "| --- | --- | --- | --- |"
  printf "%s" "$rows"
  echo
  echo "The NEAR detector results, hit by hit with the reason each is safe: [near-scan.md](near-scan.md)."
} >"$OUT"

echo
echo "wrote security/report.md and security/near-scan.md"
exit $failed
