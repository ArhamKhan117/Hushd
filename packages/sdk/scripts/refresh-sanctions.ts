/**
 * Rebuild src/sanctions-list.ts from OFAC's SDN list (the official XML export).
 *
 *   pnpm --filter @hushd/sdk refresh-sanctions            # download the current list
 *   pnpm --filter @hushd/sdk refresh-sanctions SDN.XML    # or read a file already downloaded
 *
 * Takes every "Digital Currency Address" on the list, keys it the way the SDK screens
 * (`addressKey`), and records where the list came from, its publish date and the SHA-256 of
 * the file, so anyone can rebuild the same snapshot. Review the diff, then commit it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { sha256 } from "@noble/hashes/sha2.js";
import { hex } from "@scure/base";
import { addressKey } from "../src/screening.ts";

const SOURCE = "https://sanctionslistservice.ofac.treas.gov/api/PublicationPreview/exports/SDN.XML";
const OUT = new URL("../src/sanctions-list.ts", import.meta.url);

const file = process.argv[2];
const bytes = file
  ? new Uint8Array(readFileSync(file))
  : new Uint8Array(await (await fetch(SOURCE, { signal: AbortSignal.timeout(120_000) }).then((r) => {
      if (!r.ok) throw new Error(`${SOURCE}: HTTP ${r.status}`);
      return r;
    })).arrayBuffer());
const xml = new TextDecoder().decode(bytes);

const date = /<Publish_Date>(\d{2})\/(\d{2})\/(\d{4})<\/Publish_Date>/.exec(xml);
if (!date) throw new Error("No publish date: is this OFAC's SDN.XML?");
const published = `${date[3]}-${date[1]}-${date[2]}`;

const keys = new Set<string>();
const entry = /<idType>Digital Currency Address - [^<]+<\/idType>\s*<idNumber>([^<]+)<\/idNumber>/g;
for (let m = entry.exec(xml); m; m = entry.exec(xml)) keys.add(addressKey(m[1]!));
// the list has held hundreds of addresses for years: a short one means a broken download
if (keys.size < 500) throw new Error(`Only ${keys.size} addresses: refusing to write a suspicious list`);

const sorted = [...keys].sort();
const lines = sorted.join("").match(/.{1,96}/g)!.map((l) => `    "${l}"`).join(" +\n");
writeFileSync(
  OUT,
  `// Generated by scripts/refresh-sanctions.ts from OFAC's SDN list; do not edit by hand.
// Each key is the first 8 bytes of SHA-256 of an address in normal form (src/screening.ts).
export const SANCTIONS = {
  source: "${SOURCE}",
  published: "${published}",
  sourceSha256: "${hex.encode(sha256(bytes))}",
  count: ${sorted.length},
  keys:
${lines},
} as const;
`,
);
console.log(`Wrote ${sorted.length} addresses (published ${published}) to src/sanctions-list.ts`);
