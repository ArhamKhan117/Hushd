//! Writes pool/src/poseidon_constants.rs: the round constants and MDS matrices of
//! circomlib's Poseidon (x^5, 8 full rounds) for widths 3 and 4, as Montgomery-form
//! limbs, so the contract carries only the two widths it uses.
//!
//!   cargo run -p gen-poseidon -- pool/src/poseidon_constants.rs

use ark_bn254::Fr;
use light_poseidon::parameters::bn254_x5::get_poseidon_parameters;
use std::fmt::Write;

fn limbs(x: &Fr) -> String {
    let l = x.0.0;
    format!("Fr::new_unchecked(BigInt::new([{:#018x}, {:#018x}, {:#018x}, {:#018x}]))", l[0], l[1], l[2], l[3])
}

fn main() {
    let out = std::env::args().nth(1).unwrap_or_else(|| "pool/src/poseidon_constants.rs".into());
    let mut s = String::from(
        "// Generated by contracts/tools/gen-poseidon. Do not edit by hand.\n\
         // circomlib Poseidon over BN254 (x^5, 8 full rounds), Montgomery-form limbs.\n\n\
         use ark_bn254::Fr;\nuse ark_ff::BigInt;\n",
    );
    for width in [3u8, 4u8] {
        let p = get_poseidon_parameters::<Fr>(width).expect("parameters");
        writeln!(s, "\npub const PARTIAL_ROUNDS_{width}: usize = {};", p.partial_rounds).unwrap();
        writeln!(s, "pub const ARK_{width}: [Fr; {}] = [", p.ark.len()).unwrap();
        for c in &p.ark {
            writeln!(s, "    {},", limbs(c)).unwrap();
        }
        writeln!(s, "];").unwrap();
        writeln!(s, "pub const MDS_{width}: [[Fr; {width}]; {width}] = [").unwrap();
        for row in &p.mds {
            writeln!(s, "    [{}],", row.iter().map(limbs).collect::<Vec<_>>().join(", ")).unwrap();
        }
        writeln!(s, "];").unwrap();
        assert_eq!(p.full_rounds, 8);
    }
    std::fs::write(&out, s).expect("write");
    println!("wrote {out}");
}
