#!/usr/bin/env node
/**
 * Writes contracts/pool/src/vk.rs from the circuits' verification keys
 * (build/<circuit>/<circuit>_vkey.json), in the byte layout NEAR's alt_bn128 host
 * functions read: G1 = x ‖ y, G2 = x.c0 ‖ x.c1 ‖ y.c0 ‖ y.c1, each 32 bytes LE.
 *
 *   node scripts/gen-vk-rs.mjs [out.rs]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = here.endsWith("scripts") ? join(here, "..") : here;
const out = process.argv[2] ?? join(root, "../contracts/pool/src/vk.rs");
const CIRCUITS = ["joinsplit", "receipt", "funds", "volume"];

function le32(dec) {
  let n = BigInt(dec);
  const bytes = [];
  for (let i = 0; i < 32; i++) {
    bytes.push(Number(n & 0xffn));
    n >>= 8n;
  }
  if (n !== 0n) throw new Error(`${dec} does not fit 32 bytes`);
  return bytes;
}
const g1 = (p) => {
  if (p[2] !== "1") throw new Error("G1 point is not affine");
  return [...le32(p[0]), ...le32(p[1])];
};
const g2 = (p) => {
  if (p[2][0] !== "1" || p[2][1] !== "0") throw new Error("G2 point is not affine");
  return [...le32(p[0][0]), ...le32(p[0][1]), ...le32(p[1][0]), ...le32(p[1][1])];
};
const arr = (bytes) => {
  const rows = [];
  for (let i = 0; i < bytes.length; i += 16) rows.push("        " + bytes.slice(i, i + 16).map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ") + ",");
  return `[\n${rows.join("\n")}\n    ]`;
};

let rs = `// Generated by circuits/scripts/gen-vk-rs.mjs from the circuits' verification keys.
// Do not edit by hand: rerun the script after a new trusted setup.

use crate::groth16::{G1, G2, VerifyingKey};
`;
for (const name of CIRCUITS) {
  const vk = JSON.parse(readFileSync(join(root, "build", name, `${name}_vkey.json`), "utf8"));
  if (vk.protocol !== "groth16" || vk.curve !== "bn128") throw new Error(`${name}: not a groth16 bn128 key`);
  const up = name.toUpperCase();
  rs += `
// ${name}: ${vk.nPublic} public inputs
const ${up}_ALPHA: G1 = ${arr(g1(vk.vk_alpha_1))};
const ${up}_BETA: G2 = ${arr(g2(vk.vk_beta_2))};
const ${up}_GAMMA: G2 = ${arr(g2(vk.vk_gamma_2))};
const ${up}_DELTA: G2 = ${arr(g2(vk.vk_delta_2))};
const ${up}_IC: [G1; ${vk.IC.length}] = [
${vk.IC.map((p) => "    " + arr(g1(p)).replace(/\n/g, "\n    ") + ",").join("\n")}
];

pub fn ${name}() -> VerifyingKey {
    VerifyingKey { alpha: ${up}_ALPHA, beta: ${up}_BETA, gamma: ${up}_GAMMA, delta: ${up}_DELTA, ic: ${up}_IC.to_vec() }
}
`;
}
writeFileSync(out, rs);
console.log(`wrote ${out}`);
